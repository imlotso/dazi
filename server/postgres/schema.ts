/** PostgreSQL schema 1: deliberately applied only by the operator migration. */
export const schemaVersion = 1;
export const schemaSql = `
CREATE TABLE users (
  id TEXT PRIMARY KEY, username TEXT NOT NULL, email TEXT NOT NULL, password_hash TEXT NOT NULL,
  created_at BIGINT NOT NULL, role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
  disabled_at BIGINT, auth_version BIGINT NOT NULL DEFAULT 0
);
-- SQLite NOCASE folds ASCII only. C collation keeps all other characters distinct.
CREATE UNIQUE INDEX users_username_nocase ON users ((translate(username,'ABCDEFGHIJKLMNOPQRSTUVWXYZ','abcdefghijklmnopqrstuvwxyz') COLLATE "C"));
CREATE UNIQUE INDEX users_email_nocase ON users ((translate(email,'ABCDEFGHIJKLMNOPQRSTUVWXYZ','abcdefghijklmnopqrstuvwxyz') COLLATE "C"));
CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires_at BIGINT NOT NULL
);
CREATE TABLE email_codes (
  email TEXT NOT NULL, purpose TEXT NOT NULL, code_hash TEXT NOT NULL, created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL, attempts BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(email,purpose)
);
CREATE TABLE challenges (
  id TEXT PRIMARY KEY, owner TEXT NOT NULL, language TEXT NOT NULL, difficulty TEXT NOT NULL,
  duration BIGINT NOT NULL, target TEXT NOT NULL, started_at BIGINT NOT NULL, finished_at BIGINT,
  status TEXT NOT NULL DEFAULT 'active', correct BIGINT, total BIGINT, accuracy DOUBLE PRECISION, speed DOUBLE PRECISION,
  published BIGINT NOT NULL DEFAULT 0, nickname TEXT, checkpoints BIGINT NOT NULL DEFAULT 0,
  last_checkpoint_at BIGINT, last_correct BIGINT NOT NULL DEFAULT 0, activity_flag BIGINT NOT NULL DEFAULT 0,
  review_reasons TEXT NOT NULL DEFAULT '[]', elapsed_ms BIGINT NOT NULL DEFAULT 0, active_started_at BIGINT,
  pause_count BIGINT NOT NULL DEFAULT 0, last_checkpoint_elapsed_ms BIGINT, last_client_checkpoint_elapsed_ms BIGINT,
  missing_client_checkpoint_time BIGINT NOT NULL DEFAULT 0, last_checkpoint_total BIGINT NOT NULL DEFAULT 0,
  backspaces BIGINT NOT NULL DEFAULT 0, errors BIGINT NOT NULL DEFAULT 0, article_id TEXT, article_metadata TEXT,
  typed TEXT, mode TEXT NOT NULL DEFAULT 'timed', strict BIGINT NOT NULL DEFAULT 0, ranking_removed BIGINT NOT NULL DEFAULT 0,
  recovery_key_hash TEXT, recovered BIGINT NOT NULL DEFAULT 0, claim_id TEXT, claim_version BIGINT NOT NULL DEFAULT 0,
  recovery_request_id TEXT, recovery_request_used BIGINT NOT NULL DEFAULT 0, recovered_elapsed_ms BIGINT NOT NULL DEFAULT 0,
  publish_recovered_at BIGINT, draft_id TEXT
);
CREATE TABLE scores (
  owner TEXT NOT NULL, language TEXT NOT NULL, difficulty TEXT NOT NULL, duration BIGINT NOT NULL,
  nickname TEXT NOT NULL, speed DOUBLE PRECISION NOT NULL, accuracy DOUBLE PRECISION NOT NULL,
  correct BIGINT NOT NULL, created_at BIGINT NOT NULL, attempt_id TEXT NOT NULL,
  PRIMARY KEY(owner,language,difficulty,duration)
);
CREATE TABLE workspace_items (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, kind TEXT NOT NULL, item_id TEXT NOT NULL,
  updated_at BIGINT NOT NULL, value TEXT, PRIMARY KEY(user_id,kind,item_id)
);
CREATE TABLE workspace_revisions (
  user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, revision BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE public_articles (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, author TEXT NOT NULL, theme TEXT NOT NULL, language TEXT NOT NULL,
  difficulty TEXT NOT NULL, text TEXT NOT NULL, source TEXT NOT NULL,
  status TEXT NOT NULL CHECK(status IN ('draft','published','archived','deleted')), revision BIGINT NOT NULL,
  updated_at BIGINT NOT NULL, display_order BIGINT, length BIGINT NOT NULL, search_text TEXT NOT NULL, content_hash TEXT NOT NULL
);
CREATE TABLE public_article_groups (
  article_id TEXT NOT NULL REFERENCES public_articles(id), language TEXT NOT NULL, difficulty TEXT NOT NULL,
  PRIMARY KEY(article_id,language,difficulty)
);
CREATE TABLE admin_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id TEXT NOT NULL, actor_name TEXT NOT NULL,
  action TEXT NOT NULL, target_type TEXT NOT NULL CHECK(target_type IN ('user','article','score','setting')),
  target_id TEXT NOT NULL, target_label TEXT NOT NULL, reason TEXT, created_at BIGINT NOT NULL
);
CREATE TABLE site_settings (
  id BIGINT PRIMARY KEY CHECK(id=1), settings TEXT NOT NULL, revision BIGINT NOT NULL CHECK(revision>0)
);
CREATE TABLE smtp_settings (
  id BIGINT PRIMARY KEY CHECK(id=1), revision BIGINT NOT NULL, config TEXT, updated_at BIGINT NOT NULL
);
CREATE TABLE rate_limit_entries (
  key TEXT PRIMARY KEY, count BIGINT NOT NULL, expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX rate_limit_expiry ON rate_limit_entries(expires_at);
CREATE INDEX scores_rank ON scores(language,difficulty,duration,speed DESC,accuracy DESC,created_at ASC);
CREATE INDEX challenges_owner ON challenges(owner,started_at DESC);
CREATE INDEX challenges_rank ON challenges(language,difficulty,mode,strict,finished_at)
  WHERE published=1 AND status='finished' AND ranking_removed=0;
CREATE INDEX admin_audit_target ON admin_audit(target_type,id DESC);
CREATE INDEX sessions_user ON sessions(user_id);
CREATE INDEX challenges_admin_scores ON challenges(finished_at DESC,id) WHERE published=1;
CREATE INDEX challenges_recent_finished ON challenges(finished_at,owner) WHERE finished_at IS NOT NULL;
CREATE UNIQUE INDEX catalog_public_content ON public_articles(language,content_hash) WHERE status='published';
CREATE INDEX catalog_public_groups ON public_articles(language,difficulty) WHERE status='published';
`;

export const dataTables = [
  'users', 'sessions', 'email_codes', 'challenges', 'scores', 'workspace_items', 'workspace_revisions',
  'public_articles', 'public_article_groups', 'admin_audit', 'site_settings', 'smtp_settings',
] as const;
